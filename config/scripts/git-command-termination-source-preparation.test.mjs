import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { afterEach, expect, it } from 'vitest'
import { parse } from 'yaml'
import { compileAggregateExpression } from './pr-aggregate-gate-context.mjs'
import {
  capturePluginSchemaPreparation,
  PLUGIN_SCHEMA_PREPARATION_PATHS
} from './capture-plugin-schema-preparation.mjs'

const workflow = parse(
  readFileSync('.github/workflows/git-command-termination-runtime.yml', 'utf8')
)
const roots = []

afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true })
  }
})

it('keeps source preparation manual, default-off, isolated and visibly fallible', () => {
  expect(workflow.on.workflow_dispatch.inputs.prepare_source).toMatchObject({
    type: 'boolean',
    default: false
  })
  const job = workflow.jobs['prepare-source']
  const admitted = compileAggregateExpression(job.if, ['github', 'inputs'])
  for (const event_name of ['pull_request', 'schedule', 'workflow_dispatch']) {
    for (const prepare_source of [false, true]) {
      expect(admitted({ github: { event_name }, inputs: { prepare_source } }).coerceString()).toBe(
        String(event_name === 'workflow_dispatch' && prepare_source)
      )
    }
  }
  expect(job['runs-on']).toBe('ubuntu-24.04')
  expect(job.permissions).toEqual({ contents: 'read' })
  expect(job.needs).toBeUndefined()
  const checkout = job.steps.find((step) => step.uses?.startsWith('actions/checkout@'))
  expect(checkout.with).toMatchObject({ ref: '${{ github.sha }}', 'persist-credentials': false })
  const install = job.steps.find(
    (step) => step.uses === './.github/actions/install-node-dependencies'
  )
  expect(install.with['native-runtime']).toBe('node')
  const typecheck = job.steps.find((step) => step.id === 'typecheck')
  const generation = job.steps.find((step) => step.id === 'generation')
  const capture = job.steps.find((step) => step.id === 'capture')
  expect(typecheck.run).toBe('pnpm tc')
  expect(generation.run).toBe('pnpm generate:plugin-schemas')
  for (const step of [typecheck, generation, capture]) {
    expect(step['continue-on-error']).toBeUndefined()
  }
  expect(generation.if).toBe('!cancelled()')
  expect(capture.if).toBe('!cancelled()')
  expect(capture.env.TYPECHECK_OUTCOME).toBe('${{ steps.typecheck.outcome }}')
  expect(capture.env.GENERATION_OUTCOME).toBe('${{ steps.generation.outcome }}')
  const upload = job.steps.find((step) => step.uses?.startsWith('actions/upload-artifact@'))
  expect(upload.if).toBe('always()')
  expect(upload.with.name).toBe(
    'plugin-schema-preparation-${{ github.sha }}-${{ github.run_id }}-${{ github.run_attempt }}'
  )
  expect(upload.with.path).toBe('${{ runner.temp }}/plugin-schema-preparation/')
  expect(upload.with['if-no-files-found']).toBe('error')
  for (const id of ['windows-exit', 'fork-costs']) {
    expect(workflow.jobs[id].needs).toBeUndefined()
    expect(workflow.jobs[id].steps.some((step) => step.id === 'generation')).toBe(false)
  }
})

function fixture() {
  const root = mkdtempSync(join(tmpdir(), 'orca-schema-preparation-'))
  roots.push(root)
  const checkout = join(root, 'checkout')
  mkdirSync(checkout)
  const git = (...args) => execFileSync('git', args, { cwd: checkout, encoding: 'utf8' }).trim()
  git('init', '--quiet')
  for (const path of PLUGIN_SCHEMA_PREPARATION_PATHS) {
    mkdirSync(dirname(join(checkout, path)), { recursive: true })
    writeFileSync(join(checkout, path), 'baseline\n')
  }
  git('add', '.')
  git(
    '-c',
    'user.name=CI Test',
    '-c',
    'user.email=ci@example.invalid',
    '-c',
    'commit.gpgsign=false',
    'commit',
    '--quiet',
    '-m',
    'baseline'
  )
  return {
    checkout,
    outputDir: join(root, 'artifact'),
    env: {
      GITHUB_SHA: git('rev-parse', 'HEAD'),
      GITHUB_RUN_ID: '123456',
      GITHUB_RUN_ATTEMPT: '2',
      TYPECHECK_OUTCOME: 'failure',
      GENERATION_OUTCOME: 'success'
    }
  }
}

it('captures all seven hashes and a source-bound patch without qualifying generated bytes', () => {
  const input = fixture()
  const path = PLUGIN_SCHEMA_PREPARATION_PATHS[0]
  writeFileSync(join(input.checkout, path), 'proposed\n')
  const report = capturePluginSchemaPreparation(input)
  expect(report).toMatchObject({
    diagnosticOnly: true,
    qualifiedCandidate: false,
    checkoutSha: input.env.GITHUB_SHA,
    expectedSha: input.env.GITHUB_SHA,
    runId: '123456',
    runAttempt: '2',
    typecheckOutcome: 'failure',
    generationOutcome: 'success',
    proposalStatus: 'complete',
    validationErrors: []
  })
  expect(report.files.map((file) => file.path)).toEqual(PLUGIN_SCHEMA_PREPARATION_PATHS)
  expect(report.files).toHaveLength(7)
  expect(report.files.every((file) => /^[0-9a-f]{64}$/.test(file.beforeSha256))).toBe(true)
  expect(report.files.every((file) => /^[0-9a-f]{64}$/.test(file.afterSha256))).toBe(true)
  const patch = readFileSync(join(input.outputDir, 'proposed.patch'))
  expect(report.patchSha256).toBe(createHash('sha256').update(patch).digest('hex'))
  expect(patch.toString()).toContain(`diff --git a/${path} b/${path}`)
})

it('retains a partial proposal when generation fails without qualifying it', () => {
  const input = fixture()
  input.env.GENERATION_OUTCOME = 'failure'
  writeFileSync(join(input.checkout, PLUGIN_SCHEMA_PREPARATION_PATHS[0]), 'partial\n')
  const report = capturePluginSchemaPreparation(input)
  expect(report).toMatchObject({
    diagnosticOnly: true,
    qualifiedCandidate: false,
    typecheckOutcome: 'failure',
    generationOutcome: 'failure',
    proposalStatus: 'partial',
    validationErrors: []
  })
  expect(readFileSync(join(input.outputDir, 'proposed.patch'), 'utf8')).toContain('+partial')
})

it('records a partial generator failure and rejects unexplained changes without exporting their bytes', () => {
  const input = fixture()
  input.env.GENERATION_OUTCOME = 'failure'
  writeFileSync(join(input.checkout, PLUGIN_SCHEMA_PREPARATION_PATHS[0]), 'partial\n')
  writeFileSync(join(input.checkout, 'unexplained.txt'), 'UNRELATED_CONTENT')
  expect(() => capturePluginSchemaPreparation(input)).toThrow('source preparation was rejected')
  const report = JSON.parse(readFileSync(join(input.outputDir, 'preparation.json'), 'utf8'))
  expect(report).toMatchObject({
    diagnosticOnly: true,
    qualifiedCandidate: false,
    typecheckOutcome: 'failure',
    generationOutcome: 'failure',
    proposalStatus: 'rejected',
    unexpectedPaths: ['unexplained.txt']
  })
  expect(report.validationErrors).toContain('unexpected_paths')
  expect(readFileSync(join(input.outputDir, 'proposed.patch'), 'utf8')).not.toContain(
    'UNRELATED_CONTENT'
  )
})
